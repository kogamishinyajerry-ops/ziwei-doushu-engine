def analyze_name(name: str, chart_wuxing: str = "") -> Optional[Dict]:
    """
    分析完整姓名 (自动分割姓和名).
    
    支持:
    - 单姓+单名: 王伟
    - 单姓+双名: 王伟民
    - 复姓+单名: 欧阳修
    - 复姓+双名: 欧阳修文
    
    常见复姓: 欧阳/司马/上官/诸葛/东方/慕容/皇甫/尉迟/夏侯/令狐/公孙/宇文/长孙/司徒/司空
    """
    if not name or len(name) < 2:
        return None
    
    compound_surnames = [
        "欧阳","司马","上官","诸葛","东方","慕容","皇甫","尉迟",
        "夏侯","令狐","公孙","宇文","长孙","司徒","司空","独孤",
        "南宫","申屠","闾丘","闻人","夏侯","轩辕","濮阳","淳于",
        "单于","太叔","申屠","公羊","壤驷","公良","夹谷","宰父",
        "谷梁","段干","百里","东郭","南门","呼延","羊舌","微生",
        "梁丘","左丘","东门","西门","南宫",
    ]
    
    surname = ""
    given_name = ""
    
    # 尝试复姓
    for cs in compound_surnames:
        if name.startswith(cs) and len(name) > len(cs):
            surname = cs
            given_name = name[len(cs):]
            break
    
    # 单姓
    if not surname:
        surname = name[0]
        given_name = name[1:]
    
    if not given_name:
        return None
    
    return full_name_analysis(surname, given_name, chart_wuxing)


