def get_stroke(char: str) -> int:
    """获取汉字笔画数 (康熙字典标准)."""
    if char in KANGXI_STROKES:
        return KANGXI_STROKES[char]
    # fallback: 使用 unicode 激进估算 (仅用于未知字)
    # 这只是一个近似
    code = ord(char)
    if 0x4E00 <= code <= 0x9FFF:
        # 基于 Unicode 排列估算 — 这不可靠, 但对罕见字提供基础值
        return max(1, (code - 0x4E00) // 500 + 1)
    return 1


@dataclass
class FiveGrid:
    """五格数理结果."""
    surname: str           # 姓
    given_name: str        # 名
    # 五格
    tiange: int = 0        # 天格 (姓+1)
    renge: int = 0         # 人格 (姓+名1)
    dige: int = 0          # 地格 (名1+名2)
    waige: int = 0         # 外格 (总格-人格+1)
    zongge: int = 0        # 总格 (全部)
    
    # 三才 (天格/人格/地格的五行首位)
    sancai: Tuple[str, str, str] = ("","","")
    
    # 各格数理解读
    tiange_info: Optional[NumberMeaning] = None
    renge_info: Optional[NumberMeaning] = None
    dige_info: Optional[NumberMeaning] = None
    waige_info: Optional[NumberMeaning] = None
    zongge_info: Optional[NumberMeaning] = None
    
    # 评分
    score: int = 0          # 0-100
    overall: str = ""       # 综合评价


def number_to_wuxing(n: int) -> str:
    """数理转五行 (1/2木, 3/4火, 5/6土, 7/8金, 9/10水)."""
    tail = ((n - 1) % 10) + 1
    if tail in [1, 2]: return "木"
    if tail in [3, 4]: return "火"
    if tail in [5, 6]: return "土"
    if tail in [7, 8]: return "金"
    return "水"


def get_sancai(tiange: int, renge: int, dige: int) -> Tuple[str, str, str]:
    """获取三才五行配置."""
    return (
        number_to_wuxing(tiange),
        number_to_wuxing(renge),
        number_to_wuxing(dige),
    )


def analyze_sancai(sancai: Tuple[str, str, str]) -> Dict:
    """
    分析三才配置.
    
    三才配置 (天格/人格/地格的五行关系) 是姓名学的核心,
    代表天时/人和/地利的关系.
    """
    t, r, d = sancai
    results = []
    score = 0
    
    # 天→人 (上司/长辈/环境 对 自身)
    relation_tr = WUXING_RELATION.get((t, r), ("未知",""))
    results.append({
        "type": "天格→人格 (环境/长辈→自身)",
        "wuxing": f"{t}→{r}",
        "relation": relation_tr[0],
        "desc": relation_tr[1],
    })
    
    # 人→地 (自身 对 下属/家庭/基础)
    relation_rd = WUXING_RELATION.get((r, d), ("未知",""))
    results.append({
        "type": "人格→地格 (自身→基础/家庭)",
        "wuxing": f"{r}→{d}",
        "relation": relation_rd[0],
        "desc": relation_rd[1],
    })
    
    # 天→地 (环境和基础的关系)
    relation_td = WUXING_RELATION.get((t, d), ("未知",""))
    results.append({
        "type": "天格→地格 (环境→基础)",
        "wuxing": f"{t}→{d}",
        "relation": relation_td[0],
        "desc": relation_td[1],
    })
    
    # 评分
    for r in results:
        if r["relation"] == "相生":
            score += 30
        elif r["relation"] == "比和":
            score += 20
        elif r["relation"] == "相克":
            score += 5
    
    # 描述
    all_good = all(r["relation"] in ("相生","比和") for r in results)
    all_bad = all(r["relation"] == "相克" for r in results)
    
    if all_good:
        overall = "上上配置: 三才流通, 天人地和谐统一, 运势顺遂, 事半功倍。"
    elif all_bad:
        overall = "下下配置: 三才相克, 天时地利人和皆受阻, 需加倍努力方能克服。"
    elif results[0]["relation"] in ("相生","比和"):
        overall = "中上配置: 天助自助, 但基础尚需巩固, 稳中求进。"
    else:
        overall = "中下配置: 环境压力较大, 但坚持努力可在逆境中成长。"
    
    return {
        "sancai": list(sancai),
        "relations": results,
        "score": min(100, score),
        "overall": overall,
    }


def calculate_five_grid(surname: str, given_name: str) -> FiveGrid:
    """
    计算姓名的五格数理.
    
    规则:
    - 单姓: 天格 = 姓笔画 + 1
    - 复姓: 天格 = 姓笔画总和
    - 人格 = 姓末字笔画 + 名首字笔画
    - 单名: 地格 = 名笔画 + 1
    - 双名: 地格 = 名笔画总和
    - 外格 = 总格 - 人格 + 1
    - 总格 = 全部字笔画总和
    """
    # 笔画
    surname_strokes = [get_stroke(c) for c in surname]
    given_strokes = [get_stroke(c) for c in given_name]
    
    total_surname = sum(surname_strokes)
    total_given = sum(given_strokes)
    
    # 天格
    if len(surname) == 1:
        tiange = total_surname + 1   # 单姓 +1
    else:
        tiange = total_surname        # 复姓不加
    
    # 人格
    renge = surname_strokes[-1] + given_strokes[0]
    
    # 地格
    if len(given_name) == 1:
        dige = total_given + 1        # 单名 +1
    else:
        dige = total_given
    
    # 总格
    zongge = total_surname + total_given
    
    # 外格
    waige = zongge - renge + 1
    
    fg = FiveGrid(
        surname=surname, given_name=given_name,
        tiange=tiange, renge=renge, dige=dige,
        waige=waige, zongge=zongge,
    )
    
    # 各格数理信息
    fg.tiange_info = NUMBER_81.get(tiange)
    fg.renge_info = NUMBER_81.get(renge)
    fg.dige_info = NUMBER_81.get(dige)
    fg.waige_info = NUMBER_81.get(waige)
    fg.zongge_info = NUMBER_81.get(zongge)
    
    # 三才
    fg.sancai = get_sancai(tiange, renge, dige)
    
    # 评分
    good_grids = 0
    total_grids = 0
    for info in [fg.tiange_info, fg.renge_info, fg.dige_info, fg.waige_info, fg.zongge_info]:
        if info is not None:
            total_grids += 1
            if info.is_good: good_grids += 1
    
    if total_grids > 0:
        fg.score = int(good_grids / total_grids * 60)  # base 60 score
    else:
        fg.score = 30
    
    # 三才加分
    sancai_analysis = analyze_sancai(fg.sancai)
    fg.score = min(100, fg.score + sancai_analysis["score"] * 40 // 100)
    
    # 综合评价
    if fg.score >= 85:
        fg.overall = "上上之名: 数理大吉, 三才流通, 命名精当。"
    elif fg.score >= 70:
        fg.overall = "上中之名: 数理较佳, 虽有不足但总体向好。"
    elif fg.score >= 55:
        fg.overall = "中平之名: 数理平平, 吉凶参半, 勉力可成。"
    elif fg.score >= 40:
        fg.overall = "中下之名: 数理偏弱, 需在行事上多加努力弥补。"
    else:
        fg.overall = "下等之名: 数理较弱, 建议综合考虑改名。"
    
    return fg


def full_name_analysis(surname: str, given_name: str, chart_wuxing: str = "") -> Dict:
    """
    完整姓名学分析, 可选与命盘五行局联动.
    
    Args:
        surname: 姓
        given_name: 名
        chart_wuxing: 命盘五行局 (金/木/水/火/土 或 金四局/木三局等)
    
    Returns:
        完整分析结果
    """
    fg = calculate_five_grid(surname, given_name)
    sancai_analysis = analyze_sancai(fg.sancai)
    
    result = {
        "surname": surname,
        "given_name": given_name,
        "five_grid": {
            "tiange": {"value": fg.tiange, "wuxing": number_to_wuxing(fg.tiange),
                       "info": fg.tiange_info.brief if fg.tiange_info else "未知",
                       "detail": fg.tiange_info.detail if fg.tiange_info else ""},
            "renge": {"value": fg.renge, "wuxing": number_to_wuxing(fg.renge),
                      "info": fg.renge_info.brief if fg.renge_info else "未知",
                      "detail": fg.renge_info.detail if fg.renge_info else ""},
            "dige": {"value": fg.dige, "wuxing": number_to_wuxing(fg.dige),
                     "info": fg.dige_info.brief if fg.dige_info else "未知",
                     "detail": fg.dige_info.detail if fg.dige_info else ""},
            "waige": {"value": fg.waige, "wuxing": number_to_wuxing(fg.waige),
                      "info": fg.waige_info.brief if fg.waige_info else "未知",
                      "detail": fg.waige_info.detail if fg.waige_info else ""},
            "zongge": {"value": fg.zongge, "wuxing": number_to_wuxing(fg.zongge),
                       "info": fg.zongge_info.brief if fg.zongge_info else "未知",
                       "detail": fg.zongge_info.detail if fg.zongge_info else ""},
        },
        "sancai": sancai_analysis,
        "score": fg.score,
        "overall": fg.overall,
    }
    
    # 与命盘五行联动
    if chart_wuxing:
        # 提取五行 (e.g. "金四局" → "金")
        chart_wx = chart_wuxing[0] if chart_wuxing else ""
        if chart_wx in "金木水火土":
            person_wx = number_to_wuxing(fg.renge)  # 人格五行
            relation = WUXING_RELATION.get((chart_wx, person_wx), ("未知",""))
            result["chart_wuxing_interaction"] = {
                "chart_wuxing": chart_wx,
                "name_wuxing": person_wx,
                "relation": relation[0],
                "desc": f"命盘五行({chart_wx})与姓名人格五行({person_wx}): {relation[1]}",
            }
    
    return result


